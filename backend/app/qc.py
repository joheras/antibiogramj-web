"""EUCAST QC strains and their zone-diameter QC ranges (same rules as frontend/src/qc.ts).

seed/qc/EUCAST-QC-16.0.json is generated by scripts/eucast_qc_pdf_to_json.py from "Routine and extended
internal quality control for MIC determination and disk diffusion as recommended by EUCAST", v 16.0.
"""

import json
import math
import re
from functools import cache

from .config import settings

QC_FILE = "EUCAST-QC-16.0.json"


@cache
def tables() -> dict:
    return json.loads((settings.seed_dir / "qc" / QC_FILE).read_text(encoding="utf-8"))


def source() -> str:
    t = tables()
    return f"{t['name']} v {t['version']} (valid from {t['valid_from']})"


def strain(strain_id: str | None) -> dict | None:
    return next((s for s in tables()["strains"] if s["id"] == strain_id), None) if strain_id else None


def _key(name: str, disk: str) -> str:
    return f"{re.sub(r' (iv|oral)$', '', name.lower()).strip()}|{disk.strip()}"


def qc_range(qc_strain: dict | None, name: str, disk_content: str) -> dict | None:
    key = _key(name, disk_content)
    return next((r for r in qc_strain["ranges"] if _key(r["agent"], r["disk_content"]) == key), None) if qc_strain else None


STATUS_LABEL = {"in": "In range", "low": "Out of range (too small)", "high": "Out of range (too large)",
                "no-range": "No QC range"}


def result(qc_strain: dict | None, name: str, disk_content: str, diameter_mm: float) -> tuple[dict | None, str]:
    """(range, status) with the diameter rounded to the whole millimetre (half up, like Math.round)."""
    r = qc_range(qc_strain, name, disk_content)
    if r is None:
        return None, "no-range"
    d = math.floor(diameter_mm + 0.5)
    return r, "low" if d < r["min"] else "high" if d > r["max"] else "in"


def range_label(r: dict) -> str:
    return str(r["min"]) if r["min"] == r["max"] else f"{r['min']}-{r['max']}"
